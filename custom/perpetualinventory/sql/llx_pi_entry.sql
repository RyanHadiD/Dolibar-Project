CREATE TABLE llx_pi_entry (
 rowid integer AUTO_INCREMENT PRIMARY KEY,
 entity integer NOT NULL,
 event_key varchar(128) NOT NULL,
 kind varchar(32) NOT NULL,
 date_post datetime NOT NULL,
 fk_product integer NOT NULL,
 fk_warehouse integer NOT NULL,
 fk_movement integer,
 origin_type varchar(64) NOT NULL DEFAULT '',
 origin_id integer NOT NULL DEFAULT 0,
 fk_source integer NOT NULL DEFAULT 0,
 qty decimal(24,8) NOT NULL,
 unit_cost decimal(24,8) NOT NULL,
 value_delta decimal(24,8) NOT NULL,
 balance_qty decimal(24,8) NOT NULL,
 balance_value decimal(24,8) NOT NULL,
 stock_account varchar(32) NOT NULL,
 contra_account varchar(32) NOT NULL,
 journal_posted integer NOT NULL DEFAULT 0,
 note varchar(255) NOT NULL DEFAULT '',
 fk_user integer NOT NULL,
 UNIQUE KEY uk_pi_event (entity,event_key),
 UNIQUE KEY uk_pi_movement (entity,fk_movement),
 KEY idx_pi_product (entity,fk_product,fk_warehouse,date_post),
 KEY idx_pi_origin (entity,origin_type,origin_id)
) ENGINE=innodb;
