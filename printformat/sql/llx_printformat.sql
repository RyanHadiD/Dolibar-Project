CREATE TABLE llx_printformat (
 rowid integer AUTO_INCREMENT PRIMARY KEY,
 entity integer NOT NULL,
 name varchar(128) NOT NULL,
 doctype varchar(32) NOT NULL DEFAULT 'invoice',
 template_html longtext NOT NULL,
 template_css longtext,
 page_format varchar(16) NOT NULL DEFAULT 'A4',
 custom_width decimal(8,2) NULL,
 custom_height decimal(8,2) NULL,
 orientation varchar(1) NOT NULL DEFAULT 'P',
 margin_top integer NOT NULL DEFAULT 12,
 margin_right integer NOT NULL DEFAULT 12,
 margin_bottom integer NOT NULL DEFAULT 12,
 margin_left integer NOT NULL DEFAULT 12,
 active integer NOT NULL DEFAULT 1,
 is_default integer NOT NULL DEFAULT 0,
 fk_user_author integer NOT NULL DEFAULT 0,
 fk_user_modif integer,
 datec datetime NOT NULL,
 tms timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uk_printformat_name (entity,doctype,name),
 KEY idx_printformat_active (entity,doctype,active,is_default)
) ENGINE=innodb;
